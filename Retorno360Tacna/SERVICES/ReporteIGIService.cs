        /// <summary>
        /// Estructura para devolver los 4 resultsets del query unificado
        /// </summary>
        public class ResultadoConciliacion
        {
            public System.Data.DataTable DetalleIGI { get; set; } = new System.Data.DataTable();
            public System.Data.DataTable ResumenIGI { get; set; } = new System.Data.DataTable();
            public System.Data.DataTable DetalleIVA { get; set; } = new System.Data.DataTable();
            public System.Data.DataTable ResumenIVA { get; set; } = new System.Data.DataTable();
        }

        /// <summary>
        /// Ejecuta el query unificado de conciliación IGI/IVA y devuelve las 4 tablas resultantes:
        /// 1. ConciliacionIGI (detalle por pedimento)
        /// 2. ResumenIGI (agrupado por forma de pago)
        /// 3. ConciliacionIVA (detalle IVA)
        /// 4. ResumenIVA (agrupado por forma de pago IVA)
        /// </summary>
        public ResultadoConciliacion ObtenerConciliacionIGI(string baseDatos, DateTime fechaInicio, DateTime fechaFin)
        {
            var resultado = new ResultadoConciliacion();

            try
            {
                if (string.IsNullOrWhiteSpace(baseDatos))
                {
                    throw new ArgumentException("El nombre de la base de datos no puede estar vacío", nameof(baseDatos));
                }

                if (fechaFin < fechaInicio)
                {
                    throw new ArgumentException("La fecha de fin no puede ser anterior a la fecha de inicio");
                }

                Conexion conexionCliente;
                ConexionExternaInfo infoCliente;

                try
                {
                    conexionCliente = ObtenerConexionParaBaseDatos(baseDatos);
                    infoCliente = ObtenerConexionExterna(baseDatos);
                }
                catch (Exception exConexion)
                {
#if DEBUG
                    System.Diagnostics.Debug.WriteLine($"XX Error al obtener conexión: {exConexion.Message}");
#endif
                    throw new Exception($"Error al obtener conexión para la base de datos '{baseDatos}': {exConexion.Message}", exConexion);
                }

                if (conexionCliente == null)
                {
                    throw new Exception($"No se pudo establecer la conexión para la base de datos '{baseDatos}'");
                }

                string baseGlosa = baseDatos;
                try
                {
                    int idRazon = ObtenerIdRazonDesdeBaseDatos(baseDatos);
                    var razonSocial = ObtenerRazonSocial(idRazon);

                    if (!string.IsNullOrEmpty(razonSocial.BaseDatosOrigen))
                    {
                        baseGlosa = razonSocial.BaseDatosOrigen;
#if DEBUG
                        System.Diagnostics.Debug.WriteLine($">> Base de glosa desde RAZONXTABLA.DB: {baseGlosa}");
#endif
                    }
                }
                catch (Exception exRazon)
                {
#if DEBUG
                    System.Diagnostics.Debug.WriteLine($"XX Error al determinar base de glosa: {exRazon.Message}");
#endif
                    baseGlosa = baseDatos;
                }

                Conexion conexionGlosa;
                ConexionExternaInfo infoGlosa;

                try
                {
                    conexionGlosa = ObtenerConexionParaBaseDatos(baseGlosa);
                    infoGlosa = ObtenerConexionExterna(baseGlosa);
                }
                catch (Exception exGlosa)
                {
#if DEBUG
                    System.Diagnostics.Debug.WriteLine($"XX Error al obtener conexión de glosa: {exGlosa.Message}");
#endif
                    throw new Exception($"Error al obtener conexión para la base de glosa '{baseGlosa}': {exGlosa.Message}", exGlosa);
                }

#if DEBUG
                System.Diagnostics.Debug.WriteLine($"\n=== EJECUTANDO CONCILIACION IGI/IVA ===");
                System.Diagnostics.Debug.WriteLine($"Base Cliente lógica: {baseDatos}");
                System.Diagnostics.Debug.WriteLine($"Base Glosa lógica:   {baseGlosa}");
                System.Diagnostics.Debug.WriteLine($"Conexión física cliente: {(infoCliente.TieneConexionExterna ? infoCliente.Servidor : conexionPrincipal.Servidor)} / {baseDatos}");
                System.Diagnostics.Debug.WriteLine($"Conexión física glosa:   {(infoGlosa.TieneConexionExterna ? infoGlosa.Servidor : conexionPrincipal.Servidor)} / {baseGlosa}");
                System.Diagnostics.Debug.WriteLine($"Rango: {fechaInicio:yyyy-MM-dd} a {fechaFin:yyyy-MM-dd}");
#endif

                var pedimentosCliente = new List<(string Pedimento, DateTime FechaPago, string FormaPagoIGI, decimal IGICalculado)>();
                var pedimentosGlosaIGI = new List<(string Pedimento, DateTime FechaPago, string FormaPagoIGI, decimal IGIPagado)>();
                var pedimentosGlosaIVA = new List<(string Pedimento, DateTime FechaPago, string FormaPagoIVA, decimal IVAPagado)>();

                string sqlCliente = $@"
SELECT
    DP.Adu_AduanaSecc + '-' + DP.AgP_Patente + '-' + DP.Pim_Folio AS Pedimento,
    CONVERT(date, IIF(DP.CLP_CLAVE='R1', DP.Pim_FechaPagoR1, DP.Pim_FechaPago)) AS FechaPago,
    DI.FoP_Clave AS FormaPago_IGI,
    SUM(ROUND((DI.Pid_ValorAdu * FRA.Fra_AdvGral) / 100.0, 0)) AS IGI_Calculado
FROM {SqlHelper.Quotename(baseDatos)}.dbo.Di_Pedimento DP
INNER JOIN {SqlHelper.Quotename(baseDatos)}.dbo.Di_PedimentoDet DI
    ON DI.Pim_Consecutivo = DP.Pim_Consecutivo
INNER JOIN {SqlHelper.Quotename(baseDatos)}.dbo.Ca_Farancelaria FRA
    ON FRA.Fra_Fraccion = IIF(LEFT(DI.Fra_Fraccion,2)='98', DI.Fra_FraccionORIG, DI.Fra_Fraccion)
   AND FRA.Pai_Clave='MEX'
   AND FRA.Fra_TipoOper=0
WHERE IIF(DP.CLP_CLAVE='R1', DP.Pim_FechaPagoR1, DP.Pim_FechaPago) BETWEEN @FechaInicio AND @FechaFin
  AND DI.FoP_Clave IN ('0','5')
GROUP BY
    DP.Adu_AduanaSecc,
    DP.AgP_Patente,
    DP.Pim_Folio,
    CONVERT(date, IIF(DP.CLP_CLAVE='R1', DP.Pim_FechaPagoR1, DP.Pim_FechaPago)),
    DI.FoP_Clave;";

                string sqlGlosaIGI = $@"
SELECT
    TR.GL_ADUANA + '-' + TR.GL_PATENTE + '-' + TR.GL_PEDIMENTO AS Pedimento,
    CONVERT(date, TR.Gl_FecPagoReal) AS FechaPago,
    TR.Gl_FPagoAdvalorem AS FormaPago_IGI,
    SUM(ISNULL(TR.Gl_ImporteADvalorem, 0)) AS IGI_Pagado
FROM {SqlHelper.Quotename(baseGlosa)}.dbo.TR_GLOSA TR
WHERE CONVERT(date, TR.Gl_FecPagoReal) BETWEEN @FechaInicio AND @FechaFin
  AND TR.Gl_TOper = 1
  AND TR.Gl_OrigenZipGlosa = 'S'
  AND TR.Gl_FPagoAdvalorem IN ('0','5')
GROUP BY
    TR.GL_ADUANA,
    TR.GL_PATENTE,
    TR.GL_PEDIMENTO,
    CONVERT(date, TR.Gl_FecPagoReal),
    TR.Gl_FPagoAdvalorem;";

                string sqlGlosaIVA = $@"
SELECT
    TR.GL_ADUANA + '-' + TR.GL_PATENTE + '-' + TR.GL_PEDIMENTO AS Pedimento,
    CONVERT(date, TR.Gl_FecPagoReal) AS FechaPago,
    TR.Gl_FPagoIVA AS FormaPago_IVA,
    SUM(ISNULL(TR.Gl_ImporteIVA, 0)) AS IVA_Pagado
FROM {SqlHelper.Quotename(baseGlosa)}.dbo.TR_GLOSA TR
WHERE CONVERT(date, TR.Gl_FecPagoReal) BETWEEN @FechaInicio AND @FechaFin
  AND TR.Gl_TOper = 1
  AND TR.Gl_OrigenZipGlosa = 'S'
  AND TR.Gl_FPagoIVA IN ('0','21')
GROUP BY
    TR.GL_ADUANA,
    TR.GL_PATENTE,
    TR.GL_PEDIMENTO,
    CONVERT(date, TR.Gl_FecPagoReal),
    TR.Gl_FPagoIVA
HAVING SUM(ISNULL(TR.Gl_ImporteIVA, 0)) > 0;";

                try
                {
                    using (var cnCliente = conexionCliente.ObtenerConexion())
                    {
                        cnCliente.Open();

                        using var cmdCliente = new Microsoft.Data.SqlClient.SqlCommand(sqlCliente, cnCliente);
                        cmdCliente.Parameters.AddWithValue("@FechaInicio", fechaInicio);
                        cmdCliente.Parameters.AddWithValue("@FechaFin", fechaFin);
                        cmdCliente.CommandTimeout = 300;

                        using var readerCliente = cmdCliente.ExecuteReader();
                        while (readerCliente.Read())
                        {
                            string formaPagoIGI = readerCliente.IsDBNull(2) ? string.Empty : readerCliente.GetString(2).Trim();

                            if (formaPagoIGI == "0" || formaPagoIGI == "5")
                            {
                                pedimentosCliente.Add((
                                    readerCliente.IsDBNull(0) ? string.Empty : readerCliente.GetString(0),
                                    readerCliente.IsDBNull(1) ? DateTime.MinValue : readerCliente.GetDateTime(1),
                                    formaPagoIGI,
                                    readerCliente.IsDBNull(3) ? 0m : readerCliente.GetDecimal(3)
                                ));
                            }
                        }
                    }

                    using (var cnGlosa = conexionGlosa.ObtenerConexion())
                    {
                        cnGlosa.Open();

                        using (var cmdGlosaIGI = new Microsoft.Data.SqlClient.SqlCommand(sqlGlosaIGI, cnGlosa))
                        {
                            cmdGlosaIGI.Parameters.AddWithValue("@FechaInicio", fechaInicio);
                            cmdGlosaIGI.Parameters.AddWithValue("@FechaFin", fechaFin);
                            cmdGlosaIGI.CommandTimeout = 300;

                            using var readerGlosaIGI = cmdGlosaIGI.ExecuteReader();
                            while (readerGlosaIGI.Read())
                            {
                                pedimentosGlosaIGI.Add((
                                    readerGlosaIGI.IsDBNull(0) ? string.Empty : readerGlosaIGI.GetString(0),
                                    readerGlosaIGI.IsDBNull(1) ? DateTime.MinValue : readerGlosaIGI.GetDateTime(1),
                                    readerGlosaIGI.IsDBNull(2) ? string.Empty : readerGlosaIGI.GetString(2),
                                    readerGlosaIGI.IsDBNull(3) ? 0m : readerGlosaIGI.GetDecimal(3)
                                ));
                            }
                        }

                        using var cmdGlosaIVA = new Microsoft.Data.SqlClient.SqlCommand(sqlGlosaIVA, cnGlosa);
                        cmdGlosaIVA.Parameters.AddWithValue("@FechaInicio", fechaInicio);
                        cmdGlosaIVA.Parameters.AddWithValue("@FechaFin", fechaFin);
                        cmdGlosaIVA.CommandTimeout = 300;

                        using var readerGlosaIVA = cmdGlosaIVA.ExecuteReader();
                        while (readerGlosaIVA.Read())
                        {
                            pedimentosGlosaIVA.Add((
                                readerGlosaIVA.IsDBNull(0) ? string.Empty : readerGlosaIVA.GetString(0),
                                readerGlosaIVA.IsDBNull(1) ? DateTime.MinValue : readerGlosaIVA.GetDateTime(1),
                                readerGlosaIVA.IsDBNull(2) ? string.Empty : readerGlosaIVA.GetString(2),
                                readerGlosaIVA.IsDBNull(3) ? 0m : readerGlosaIVA.GetDecimal(3)
                            ));
                        }
                    }
                }
                catch (Microsoft.Data.SqlClient.SqlException sqlEx)
                {
#if DEBUG
                    System.Diagnostics.Debug.WriteLine($"XX Error al ejecutar consulta de conciliación:");
                    System.Diagnostics.Debug.WriteLine($"   Mensaje: {sqlEx.Message}");
                    System.Diagnostics.Debug.WriteLine($"   Número: {sqlEx.Number}");
                    System.Diagnostics.Debug.WriteLine($"   Línea: {sqlEx.LineNumber}");
                    System.Diagnostics.Debug.WriteLine($"   Procedimiento: {sqlEx.Procedure}");
#endif
                    throw new Exception($"Error al ejecutar consulta de conciliación: {sqlEx.Message} (Error SQL: {sqlEx.Number}, Línea: {sqlEx.LineNumber})", sqlEx);
                }

                var detalleIGI = new System.Data.DataTable();
                detalleIGI.Columns.Add("Pedimento", typeof(string));
                detalleIGI.Columns.Add("FechaPago", typeof(DateTime));
                detalleIGI.Columns.Add("FormaPago_IGI", typeof(string));
                detalleIGI.Columns.Add("IGI_Pagado", typeof(decimal));
                detalleIGI.Columns.Add("IGI_Calculado", typeof(decimal));
                detalleIGI.Columns.Add("Diferencia_IGI", typeof(decimal));
                detalleIGI.Columns.Add("Estatus", typeof(string));

                var resumenIGI = new System.Data.DataTable();
                resumenIGI.Columns.Add("Año", typeof(int));
                resumenIGI.Columns.Add("Mes", typeof(int));
                resumenIGI.Columns.Add("FormaPago_IGI", typeof(string));
                resumenIGI.Columns.Add("IGI_Pagado", typeof(decimal));
                resumenIGI.Columns.Add("IGI_Calculado", typeof(decimal));
                resumenIGI.Columns.Add("Diferencia_IGI", typeof(decimal));

                var detalleIVA = new System.Data.DataTable();
                detalleIVA.Columns.Add("Pedimento", typeof(string));
                detalleIVA.Columns.Add("FechaPago", typeof(DateTime));
                detalleIVA.Columns.Add("FormaPago_IVA", typeof(string));
                detalleIVA.Columns.Add("IVA_Pagado", typeof(decimal));

                var resumenIVA = new System.Data.DataTable();
                resumenIVA.Columns.Add("Año", typeof(int));
                resumenIVA.Columns.Add("Mes", typeof(int));
                resumenIVA.Columns.Add("FormaPago_IVA", typeof(string));
                resumenIVA.Columns.Add("IVA_Pagado", typeof(decimal));

                var glosaIGIPorClave = pedimentosGlosaIGI
                    .GroupBy(x => x.Pedimento + "|" + x.FormaPagoIGI, StringComparer.OrdinalIgnoreCase)
                    .ToDictionary(g => g.Key, g => g.ToList(), StringComparer.OrdinalIgnoreCase);

                foreach (var cliente in pedimentosCliente.OrderBy(x => x.Pedimento).ThenBy(x => x.FormaPagoIGI))
                {
                    string clave = cliente.Pedimento + "|" + cliente.FormaPagoIGI;
                    decimal igiPagadoReal = 0m;

                    if (glosaIGIPorClave.TryGetValue(clave, out var coincidencias) && coincidencias.Count > 0)
                    {
                        igiPagadoReal = coincidencias.Sum(x => x.IGIPagado);
                    }

                    decimal igiPagadoMostrado = cliente.FormaPagoIGI == "5" ? 0m : igiPagadoReal;
                    decimal diferencia = cliente.IGICalculado - igiPagadoMostrado;
                    string estatus = Math.Abs(cliente.IGICalculado - igiPagadoReal) > 1 ? "DIFERENCIA" : "OK";

                    detalleIGI.Rows.Add(
                        cliente.Pedimento,
                        cliente.FechaPago,
                        cliente.FormaPagoIGI,
                        igiPagadoMostrado,
                        cliente.IGICalculado,
                        diferencia,
                        estatus);
                }

                foreach (System.Data.DataRow r in detalleIGI.Rows)
                {
                    // iteración forzada para evitar resolución errónea de AsEnumerable por PLINQ
                }

                var resumenIGIGroups = detalleIGI.Rows.Cast<System.Data.DataRow>()
                    .Where(r =>
                    {
                        var forma = Convert.ToString(r["FormaPago_IGI"])?.Trim();
                        return forma == "0" || forma == "5";
                    })
                    .GroupBy(r => new
                    {
                        Anio = ((DateTime)r["FechaPago"]).Year,
                        Mes = ((DateTime)r["FechaPago"]).Month,
                        Forma = Convert.ToString(r["FormaPago_IGI"])?.Trim() ?? string.Empty
                    })
                    .OrderBy(g => g.Key.Anio)
                    .ThenBy(g => g.Key.Mes)
                    .ThenBy(g => g.Key.Forma);

                foreach (var grp in resumenIGIGroups)
                {
                    decimal igiPagado = grp.Sum(r => Convert.ToDecimal(r["IGI_Pagado"]));
                    decimal igiCalculado = grp.Sum(r => Convert.ToDecimal(r["IGI_Calculado"]));
                    decimal diferencia = grp.Sum(r => Convert.ToDecimal(r["Diferencia_IGI"]));

                    resumenIGI.Rows.Add(grp.Key.Anio, grp.Key.Mes, grp.Key.Forma, igiPagado, igiCalculado, diferencia);
                }

                var pedimentosClienteDistinct = pedimentosCliente
                    .Select(x => x.Pedimento)
                    .ToHashSet(StringComparer.OrdinalIgnoreCase);

                foreach (var row in pedimentosGlosaIVA
                    .Where(x => pedimentosClienteDistinct.Contains(x.Pedimento))
                    .OrderBy(x => x.Pedimento)
                    .ThenBy(x => x.FormaPagoIVA))
                {
                    detalleIVA.Rows.Add(row.Pedimento, row.FechaPago, row.FormaPagoIVA, row.IVAPagado);
                }

                var resumenIVAGroups = detalleIVA.Rows.Cast<System.Data.DataRow>()
                    .GroupBy(r => new
                    {
                        Anio = ((DateTime)r["FechaPago"]).Year,
                        Mes = ((DateTime)r["FechaPago"]).Month,
                        Forma = Convert.ToString(r["FormaPago_IVA"]) ?? string.Empty
                    })
                    .OrderBy(g => g.Key.Anio)
                    .ThenBy(g => g.Key.Mes)
                    .ThenBy(g => g.Key.Forma);

                foreach (var grp in resumenIVAGroups)
                {
                    decimal ivaPagado = grp.Sum(r => Convert.ToDecimal(r["IVA_Pagado"]));
                    resumenIVA.Rows.Add(grp.Key.Anio, grp.Key.Mes, grp.Key.Forma, ivaPagado);
                }

                resultado.DetalleIGI = detalleIGI;
                resultado.ResumenIGI = resumenIGI;
                resultado.DetalleIVA = detalleIVA;
                resultado.ResumenIVA = resumenIVA;

#if DEBUG
                System.Diagnostics.Debug.WriteLine($">> Pedimentos cliente: {pedimentosCliente.Count} registros");
                System.Diagnostics.Debug.WriteLine($">> Pedimentos glosa IGI: {pedimentosGlosaIGI.Count} registros");
                System.Diagnostics.Debug.WriteLine($">> Pedimentos glosa IVA: {pedimentosGlosaIVA.Count} registros");
                System.Diagnostics.Debug.WriteLine($">> Detalle IGI: {resultado.DetalleIGI.Rows.Count} registros");
                System.Diagnostics.Debug.WriteLine($">> Resumen IGI: {resultado.ResumenIGI.Rows.Count} formas de pago");
                System.Diagnostics.Debug.WriteLine($">> Detalle IVA: {resultado.DetalleIVA.Rows.Count} registros");
                System.Diagnostics.Debug.WriteLine($">> Resumen IVA: {resultado.ResumenIVA.Rows.Count} formas de pago");
#endif
            }
            catch (Microsoft.Data.SqlClient.SqlException sqlEx)
            {
#if DEBUG
                System.Diagnostics.Debug.WriteLine($"\nXX ERROR SQL en ObtenerConciliacionIGI:");
                System.Diagnostics.Debug.WriteLine($"   Mensaje: {sqlEx.Message}");
                System.Diagnostics.Debug.WriteLine($"   Número de error: {sqlEx.Number}");
                System.Diagnostics.Debug.WriteLine($"   Línea: {sqlEx.LineNumber}");
                System.Diagnostics.Debug.WriteLine($"   Procedimiento: {sqlEx.Procedure}");
                System.Diagnostics.Debug.WriteLine($"   Servidor: {sqlEx.Server}");
                System.Diagnostics.Debug.WriteLine($"   Stack: {sqlEx.StackTrace}");
#endif
                throw new Exception($"Error SQL al obtener conciliación IGI/IVA: {sqlEx.Message} (Número: {sqlEx.Number}, Línea: {sqlEx.LineNumber})", sqlEx);
            }
            catch (ArgumentException)
            {
                throw;
            }
            catch (Exception ex)
            {
#if DEBUG
                System.Diagnostics.Debug.WriteLine($"\nXX ERROR GENERAL en ObtenerConciliacionIGI:");
                System.Diagnostics.Debug.WriteLine($"   Tipo: {ex.GetType().Name}");
                System.Diagnostics.Debug.WriteLine($"   Mensaje: {ex.Message}");
                if (ex.InnerException != null)
                {
                    System.Diagnostics.Debug.WriteLine($"   Inner Exception: {ex.InnerException.Message}");
                }
                System.Diagnostics.Debug.WriteLine($"   Stack: {ex.StackTrace}");
#endif
                throw new Exception($"Error al obtener conciliación IGI/IVA: {ex.Message}", ex);
            }

            return resultado;
        }

        /// <summary>
        /// Ejecuta el flujo de resumen tal como el query suministrado por el usuario.
        /// Devuelve dos DataTables: (IGI, IVA) con las columnas equivalentes al query original.
        /// La lógica intenta resolver la conexión del cliente y la de glosa según la razón social
        /// asociada a la base cliente; si no se encuentra otra base de glosa, usa la misma base cliente.
        /// </summary>
        public (System.Data.DataTable IGI, System.Data.DataTable IVA) ObtenerResumenTablasPorBase(string baseDatos, DateTime fechaInicio, DateTime fechaFin)
        {
            // Helpers internos
            var tablaIGI = new System.Data.DataTable();
            tablaIGI.Columns.Add("Año", typeof(int));
            tablaIGI.Columns.Add("Mes", typeof(int));
            tablaIGI.Columns.Add("IGI_Pagado", typeof(decimal));
            tablaIGI.Columns.Add("IGI_Calculado", typeof(decimal));
            tablaIGI.Columns.Add("Diferencia_IGI", typeof(decimal));
            tablaIGI.Columns.Add("FormaPago_IGI", typeof(string));

            var tablaIVA = new System.Data.DataTable();
            tablaIVA.Columns.Add("Año", typeof(int));
            tablaIVA.Columns.Add("Mes", typeof(int));
            tablaIVA.Columns.Add("IVA_Pagado", typeof(decimal));
            tablaIVA.Columns.Add("FormaPago_IVA", typeof(string));

            try
            {
                // Determinar conexión cliente
                var conexionCliente = ObtenerConexionParaBaseDatos(baseDatos);

                // Determinar posible base de glosa para la misma razón social
                string baseGlosa = baseDatos;
                try
                {
                    int idRazon = ObtenerIdRazonDesdeBaseDatos(baseDatos);
                    var razonSocial = ObtenerRazonSocial(idRazon);

                    // El campo DB de RAZONXTABLA contiene la base de glosa (TR_GLOSA)
                    if (!string.IsNullOrEmpty(razonSocial.BaseDatosOrigen))
                    {
                        baseGlosa = razonSocial.BaseDatosOrigen;
#if DEBUG
                        System.Diagnostics.Debug.WriteLine($"?? Base de glosa encontrada: {baseGlosa}");
#endif
                    }
                    else
                    {
#if DEBUG
                        System.Diagnostics.Debug.WriteLine($"?? Usando misma base para glosa: {baseGlosa}");
#endif
                    }
                }
                catch (Exception exRazon)
                {
#if DEBUG
                    System.Diagnostics.Debug.WriteLine($"?? Error al determinar raz?n social: {exRazon.Message}");
#endif
                    // Si no podemos determinar razon social, usar la misma base para glosa
                    baseGlosa = baseDatos;
                }

                var conexionGlosa = ObtenerConexionParaBaseDatos(baseGlosa);

                // VALIDAR CONEXI?N GLOSA
                if (!ValidarConexionYBaseDatos(conexionGlosa, baseGlosa))
                {
#if DEBUG
                    System.Diagnostics.Debug.WriteLine($"?? ERROR: No se pudo conectar a la base de glosa '{baseGlosa}'");
#endif
                    throw new Exception($"No se pudo conectar a la base de glosa '{baseGlosa}'. Verifique que la base exista y la conexi?n sea correcta.");
                }

                // Cargar pedimentos del cliente
                var pedimentosCliente = new List<(string Pedimento, DateTime? FechaPago, decimal IGI_Calculado, string FormaPago)>();
#if DEBUG
                System.Diagnostics.Debug.WriteLine($"\n--- CONSULTANDO PEDIMENTOS CLIENTE ({baseDatos}) ---");
#endif
                using (var cn = conexionCliente.ObtenerConexion())
                {
                    cn.Open();
#if DEBUG
                    System.Diagnostics.Debug.WriteLine($"?? Conexi?n cliente abierta: {cn.Database} en {cn.DataSource}");
#endif
                    string sqlCliente = $@"
SELECT 
    DP.Pim_Consecutivo AS iDPedimento,
    DP.Adu_AduanaSecc + '-' + DP.AgP_Patente + '-' + DP.Pim_Folio AS Pedimento,
    IIF(DP.CLP_CLAVE= 'R1',DP.Pim_FechaPagoR1,DP.Pim_FechaPago) AS FechaPago,
    SUM(ROUND((DI.Pid_ValorAdu * FRA.Fra_AdvGral) / 100,0)) AS IGI_Calculado,
    DI.FoP_Clave AS FormaPago_IGI
FROM {SqlHelper.Quotename(baseDatos)}.dbo.Di_Pedimento DP
INNER JOIN {SqlHelper.Quotename(baseDatos)}.dbo.Di_PedimentoDet DI ON DI.Pim_Consecutivo = DP.Pim_Consecutivo
INNER JOIN {SqlHelper.Quotename(baseDatos)}.dbo.Ca_Farancelaria FRA ON FRA.Fra_Fraccion = IIF(LEFT(DI.Fra_Fraccion,2)= '98', DI.Fra_FraccionORIG,DI.Fra_Fraccion)
    AND FRA.Pai_Clave = 'MEX'
    AND FRA.Fra_TipoOper = 0
WHERE 
    IIF(DP.CLP_CLAVE= 'R1',DP.Pim_FechaPagoR1,DP.Pim_FechaPago) BETWEEN @FechaInicio AND @FechaFin
GROUP BY  
    DP.Pim_Consecutivo,
    DP.Adu_AduanaSecc,
    DP.AgP_Patente,
    DP.Pim_Folio,
    IIF(DP.CLP_CLAVE= 'R1',DP.Pim_FechaPagoR1,DP.Pim_FechaPago),
    DI.FoP_Clave
";

#if DEBUG
                    System.Diagnostics.Debug.WriteLine($"   Parámetros: @FechaInicio={fechaInicio:yyyy-MM-dd}, @FechaFin={fechaFin:yyyy-MM-dd}");
#endif

                    using var cmd = new Microsoft.Data.SqlClient.SqlCommand(sqlCliente, cn);
                    cmd.Parameters.AddWithValue("@FechaInicio", fechaInicio);
                    cmd.Parameters.AddWithValue("@FechaFin", fechaFin);
                    cmd.CommandTimeout = 120;

                    using var rdr = cmd.ExecuteReader();
                    while (rdr.Read())
                    {
                        string ped = rdr.IsDBNull(1) ? string.Empty : rdr.GetString(1);
                        DateTime? fp = rdr.IsDBNull(2) ? (DateTime?)null : rdr.GetDateTime(2);
                        decimal igiCalc = rdr.IsDBNull(3) ? 0m : rdr.GetDecimal(3);
                        string fpago = rdr.IsDBNull(4) ? string.Empty : rdr.GetString(4);
                        pedimentosCliente.Add((ped, fp, igiCalc, fpago));
                    }
                }
#if DEBUG
                System.Diagnostics.Debug.WriteLine($"?? Pedimentos cliente encontrados: {pedimentosCliente.Count}");
                if (pedimentosCliente.Count > 0)
                {
                    var muestra = pedimentosCliente.Take(3).ToList();
                    foreach (var p in muestra)
                    {
                        System.Diagnostics.Debug.WriteLine($"      - {p.Pedimento} | FP: {p.FechaPago:yyyy-MM-dd} | IGI: ${p.IGI_Calculado:N2} | Forma: {p.FormaPago}");
                    }
                    if (pedimentosCliente.Count > 3)
                        System.Diagnostics.Debug.WriteLine($"      ... y {pedimentosCliente.Count - 3} más");
                }
                else
                {
                    System.Diagnostics.Debug.WriteLine($"   ?? NO se encontraron pedimentos en la base cliente para el rango de fechas");
                }
#endif

                // Cargar pedimentos de glosa IGI
                var pedimentosGlosaIGI = new List<(string Pedimento, DateTime FechaPago, string FormaPagoIGI, decimal IGI_Pagado)>();
#if DEBUG
                System.Diagnostics.Debug.WriteLine($"\n--- CONSULTANDO GLOSA IGI ({baseGlosa}) ---");
#endif
                using (var cn = conexionGlosa.ObtenerConexion())
                {
                    cn.Open();
#if DEBUG
                    System.Diagnostics.Debug.WriteLine($"?? Conexi?n glosa abierta: {cn.Database} en {cn.DataSource}");
#endif
                    string sqlGlosaIGI = $@"
                                            SELECT 
                                                TR.GL_ADUANA + '-' + TR.GL_PATENTE + '-' + TR.GL_PEDIMENTO AS Pedimento,
                                                CONVERT(DATE, TR.Gl_FecPagoReal) AS FechaPago,
                                                SUM(ISNULL(TR.Gl_ImporteADvalorem,0)) AS IGI_Pagado,
                                                TR.Gl_FPagoAdvalorem AS FormaPago_IGI
                                            FROM {SqlHelper.Quotename(baseGlosa)}.DBO.TR_GLOSA TR
                                            WHERE 
                                                CONVERT(DATE,TR.Gl_FecPagoReal) BETWEEN @FechaInicio AND @FechaFin
                                                AND TR.Gl_TOper = 1
                                                AND TR.Gl_OrigenZipGlosa = 'S'
                                                AND (
                                                    TR.Gl_FPagoAdvalorem IN ('0','5')
                                                )
                                            GROUP BY  
                                                TR.GL_ADUANA + '-' + TR.GL_PATENTE + '-' + TR.GL_PEDIMENTO
                                                ,CONVERT(DATE, TR.Gl_FecPagoReal)
                                                ,TR.Gl_FPagoAdvalorem
                                            HAVING SUM(ISNULL(TR.Gl_ImporteADvalorem,0)) > 0 ";

                    using var cmd = new Microsoft.Data.SqlClient.SqlCommand(sqlGlosaIGI, cn);
                    cmd.Parameters.AddWithValue("@FechaInicio", fechaInicio);
                    cmd.Parameters.AddWithValue("@FechaFin", fechaFin);
                    cmd.CommandTimeout = 120;

                    using var rdr = cmd.ExecuteReader();
                    while (rdr.Read())
                    {
                        string ped = rdr.IsDBNull(0) ? string.Empty : rdr.GetString(0);
                        DateTime fp = rdr.IsDBNull(1) ? DateTime.MinValue : rdr.GetDateTime(1);
                        decimal igiPag = rdr.IsDBNull(2) ? 0m : rdr.GetDecimal(2);
                        string fpago = rdr.IsDBNull(3) ? string.Empty : rdr.GetString(3);
                        pedimentosGlosaIGI.Add((ped, fp, fpago, igiPag));
                    }
                }
#if DEBUG
                System.Diagnostics.Debug.WriteLine($"?? Pedimentos glosa IGI encontrados: {pedimentosGlosaIGI.Count}");
                if (pedimentosGlosaIGI.Count > 0)
                {
                    var muestra = pedimentosGlosaIGI.Take(3).ToList();
                    foreach (var p in muestra)
                    {
                        System.Diagnostics.Debug.WriteLine($"      - {p.Pedimento} | FP: {p.FechaPago:yyyy-MM-dd} | IGI: ${p.IGI_Pagado:N2} | Forma: {p.FormaPagoIGI}");
                    }
                    if (pedimentosGlosaIGI.Count > 3)
                        System.Diagnostics.Debug.WriteLine($"      ... y {pedimentosGlosaIGI.Count - 3} más");
                }
                else
                {
                    System.Diagnostics.Debug.WriteLine($"   ?? NO se encontraron pedimentos en TR_GLOSA para el rango de fechas");
                }
#endif

                // Cargar pedimentos de glosa IVA
                var pedimentosGlosaIVA = new List<(string Pedimento, DateTime FechaPago, string FormaPagoIVA, decimal IVAPagado)>();
#if DEBUG
                System.Diagnostics.Debug.WriteLine($"\n--- CONSULTANDO GLOSA IVA ({baseGlosa}) ---");
#endif
                using (var cn = conexionGlosa.ObtenerConexion())
                {
                    cn.Open();
                    string sqlGlosaIVA = $@"
                                            SELECT 
                                                TR.GL_ADUANA + '-' + TR.GL_PATENTE + '-' + TR.GL_PEDIMENTO AS Pedimento,
                                                CONVERT(DATE, TR.Gl_FecPagoReal) AS FechaPago,
                                                SUM(ISNULL(TR.Gl_ImporteIVA,0)) AS IVA_Pagado,
                                                TR.Gl_FPagoIVA AS FormaPago_IVA
                                            FROM {SqlHelper.Quotename(baseGlosa)}.DBO.TR_GLOSA TR
                                            WHERE 
                                                CONVERT(DATE,TR.Gl_FecPagoReal) BETWEEN @FechaInicio AND @FechaFin
                                                AND TR.Gl_TOper = 1
                                                AND TR.Gl_OrigenZipGlosa = 'S'
                                                AND (
                                                    TR.Gl_FPagoIVA IN ('0','21') 
                                                )
                                            GROUP BY  
                                                TR.GL_ADUANA + '-' + TR.GL_PATENTE + '-' + TR.GL_PEDIMENTO
                                                ,CONVERT(DATE, TR.Gl_FecPagoReal)
                                                ,TR.Gl_FPagoIVA
                                            HAVING SUM(ISNULL(TR.Gl_ImporteIVA,0)) > 0
                                            ";

                    using var cmd = new Microsoft.Data.SqlClient.SqlCommand(sqlGlosaIVA, cn);
                    cmd.Parameters.AddWithValue("@FechaInicio", fechaInicio);
                    cmd.Parameters.AddWithValue("@FechaFin", fechaFin);
                    cmd.CommandTimeout = 120;

                    using var rdr = cmd.ExecuteReader();
                    while (rdr.Read())
                    {
                        string ped = rdr.IsDBNull(0) ? string.Empty : rdr.GetString(0);
                        DateTime fp = rdr.IsDBNull(1) ? DateTime.MinValue : rdr.GetDateTime(1);
                        decimal ivaPag = rdr.IsDBNull(2) ? 0m : rdr.GetDecimal(2);
                        string fpago = rdr.IsDBNull(3) ? string.Empty : rdr.GetString(3);
                        pedimentosGlosaIVA.Add((ped, fp, fpago, ivaPag));
                    }
                }
#if DEBUG
                System.Diagnostics.Debug.WriteLine($"?? Pedimentos glosa IVA encontrados: {pedimentosGlosaIVA.Count}");
#endif

                #if DEBUG
                System.Diagnostics.Debug.WriteLine($"\n--- PROCESANDO JOIN IGI ---");
#endif

                // Calcular tabla IGI: join entre pedimentosGlosaIGI y pedimentosCliente por Pedimento y FormaPago
#if DEBUG
                // Análisis de coincidencias antes del JOIN
                var pedimentosClienteSet = pedimentosCliente.Select(p => p.Pedimento).Distinct().ToHashSet();
                var pedimentosGlosaSet = pedimentosGlosaIGI.Select(p => p.Pedimento).Distinct().ToHashSet();
                var pedimentosComunes = pedimentosClienteSet.Intersect(pedimentosGlosaSet).ToList();

                System.Diagnostics.Debug.WriteLine($"   ?? Pedimentos únicos en cliente: {pedimentosClienteSet.Count}");
                System.Diagnostics.Debug.WriteLine($"   ?? Pedimentos únicos en glosa IGI: {pedimentosGlosaSet.Count}");
                System.Diagnostics.Debug.WriteLine($"   ?? Pedimentos en común: {pedimentosComunes.Count}");

                if (pedimentosComunes.Count > 0)
                {
                    System.Diagnostics.Debug.WriteLine($"   Ejemplos de pedimentos coincidentes:");
                    foreach (var ped in pedimentosComunes.Take(5))
                    {
                        System.Diagnostics.Debug.WriteLine($"      - {ped}");
                    }
                }
                else if (pedimentosClienteSet.Count > 0 && pedimentosGlosaSet.Count > 0)
                {
                    System.Diagnostics.Debug.WriteLine($"   ?? NO hay coincidencias entre pedimentos cliente y glosa");
                    System.Diagnostics.Debug.WriteLine($"   Muestra cliente: {string.Join(", ", pedimentosClienteSet.Take(3))}");
                    System.Diagnostics.Debug.WriteLine($"   Muestra glosa: {string.Join(", ", pedimentosGlosaSet.Take(3))}");
                }
#endif

                var joinIGI = from g in pedimentosGlosaIGI
                              join c in pedimentosCliente on new { g.Pedimento, FormaPago = g.FormaPagoIGI } equals new { c.Pedimento, FormaPago = c.FormaPago }
                              group new { g, c } by new { Anio = g.FechaPago.Year, Mes = g.FechaPago.Month, Forma = g.FormaPagoIGI } into grp
                              select new
                              {
                                  grp.Key.Anio,
                                  grp.Key.Mes,
                                  Forma = grp.Key.Forma,
                                  IGI_Pagado = grp.Sum(x => x.g.IGI_Pagado),
                                  IGI_Calculado = grp.Sum(x => x.c.IGI_Calculado)
                              };

                var listaJoinIGI = joinIGI.ToList();
#if DEBUG
                System.Diagnostics.Debug.WriteLine($"? Registros IGI después del JOIN: {listaJoinIGI.Count}");
                if (listaJoinIGI.Count > 0)
                {
                    foreach (var item in listaJoinIGI.Take(3))
                    {
                        System.Diagnostics.Debug.WriteLine($"      - {item.Anio}/{item.Mes:D2} Forma {item.Forma}: Pagado ${item.IGI_Pagado:N2}, Calculado ${item.IGI_Calculado:N2}");
                    }
                }
                else
                {
                    System.Diagnostics.Debug.WriteLine($"   ?? El JOIN de IGI resultó en 0 registros");
                }
#endif

                foreach (var row in listaJoinIGI.OrderBy(r => r.Anio).ThenBy(r => r.Mes).ThenBy(r => r.Forma))
                {
                    decimal igiPagado = row.IGI_Pagado;
                    decimal igiCalculado = row.IGI_Calculado;
                    decimal diferencia;

                    // Si la forma de pago es '5', el IGI_Pagado se considera 0 para el cálculo de diferencia
                    if (row.Forma == "5")
                    {
                        diferencia = 0m - igiCalculado;
                        igiPagado = 0m;
                    }
                    else
                    {
                        diferencia = igiCalculado - igiPagado;
                    }

                    tablaIGI.Rows.Add(row.Anio, row.Mes, igiPagado, igiCalculado, diferencia, row.Forma);
                }

                #if DEBUG
                System.Diagnostics.Debug.WriteLine($"\n--- PROCESANDO JOIN IVA ---");
#endif

                // Calcular tabla IVA: join entre pedimentosGlosaIVA y distinct pedimentosCliente
                var pedimentosClienteDistinct = pedimentosCliente.Select(p => p.Pedimento).Distinct().ToHashSet();

                var joinIVA = from g in pedimentosGlosaIVA
                              where pedimentosClienteDistinct.Contains(g.Pedimento)
                              group g by new { Anio = g.FechaPago.Year, Mes = g.FechaPago.Month, Forma = g.FormaPagoIVA } into grp
                              select new
                              {
                                  grp.Key.Anio,
                                  grp.Key.Mes,
                                  Forma = grp.Key.Forma,
                                  IVA_Pagado = grp.Sum(x => x.IVAPagado)
                              };

                foreach (var row in joinIVA.OrderBy(r => r.Anio).ThenBy(r => r.Mes).ThenBy(r => r.Forma))
                {
                    tablaIVA.Rows.Add(row.Anio, row.Mes, row.IVA_Pagado, row.Forma);
                }
            }
            catch (Exception ex)
            {
                throw new Exception($"Error al obtener resumen por base: {ex.Message}", ex);
            }

            return (tablaIGI, tablaIVA);
        }

        /// <summary>
        /// Valida que la conexi?n funcione y que la base de datos exista
        /// </summary>
        private bool ValidarConexionYBaseDatos(CNX.Conexion conexion, string nombreBaseDatos)
        {
            try
            {
                using (var cn = conexion.ObtenerConexion())
                {
                    cn.Open();
#if DEBUG
                    System.Diagnostics.Debug.WriteLine($"?? Validando conexi?n: {cn.DataSource} / {cn.Database}");
#endif

                    // Verificar que la base de datos exista
                    string sqlVerificarBD = @"
                        SELECT COUNT(*) 
                        FROM sys.databases 
                        WHERE name = @NombreBaseDatos";

                    using (var cmd = new Microsoft.Data.SqlClient.SqlCommand(sqlVerificarBD, cn))
                    {
                        cmd.Parameters.AddWithValue("@NombreBaseDatos", nombreBaseDatos);
                        int count = (int)cmd.ExecuteScalar();

                        if (count == 0)
                        {
#if DEBUG
                            System.Diagnostics.Debug.WriteLine($"?? Base de datos '{nombreBaseDatos}' NO existe en {cn.DataSource}");
#endif
                            return false;
                        }
                    }

                    // Verificar que las tablas necesarias existan
                    string sqlVerificarTablas = $@"
                        SELECT 
                            (SELECT COUNT(*) FROM {SqlHelper.Quotename(nombreBaseDatos)}.INFORMATION_SCHEMA.TABLES WHERE TABLE_NAME = 'Di_Pedimento') AS TienePedimento,
                            (SELECT COUNT(*) FROM {SqlHelper.Quotename(nombreBaseDatos)}.INFORMATION_SCHEMA.TABLES WHERE TABLE_NAME = 'Di_PedimentoDet') AS TienePedimentoDet,
                            (SELECT COUNT(*) FROM {SqlHelper.Quotename(nombreBaseDatos)}.INFORMATION_SCHEMA.TABLES WHERE TABLE_NAME = 'Ca_Farancelaria') AS TieneFarancelaria,
                            (SELECT COUNT(*) FROM {SqlHelper.Quotename(nombreBaseDatos)}.INFORMATION_SCHEMA.TABLES WHERE TABLE_NAME = 'TR_GLOSA') AS TieneGlosa";

                    using (var cmd = new Microsoft.Data.SqlClient.SqlCommand(sqlVerificarTablas, cn))
                    {
                        using (var reader = cmd.ExecuteReader())
                        {
                            if (reader.Read())
                            {
                                int tienePedimento = reader.GetInt32(0);
                                int tienePedimentoDet = reader.GetInt32(1);
                                int tieneFarancelaria = reader.GetInt32(2);
                                int tieneGlosa = reader.GetInt32(3);

#if DEBUG
                                System.Diagnostics.Debug.WriteLine($"   Di_Pedimento: {(tienePedimento > 0 ? "S?" : "NO")}");
                                System.Diagnostics.Debug.WriteLine($"   Di_PedimentoDet: {(tienePedimentoDet > 0 ? "S?" : "NO")}");
                                System.Diagnostics.Debug.WriteLine($"   Ca_Farancelaria: {(tieneFarancelaria > 0 ? "S?" : "NO")}");
                                System.Diagnostics.Debug.WriteLine($"   TR_GLOSA: {(tieneGlosa > 0 ? "S?" : "NO")}");
#endif

                                return tienePedimento > 0 && tienePedimentoDet > 0 && tieneFarancelaria > 0 && tieneGlosa > 0;
                            }
                        }
                    }
                }
            }
            catch (Exception ex)
            {
#if DEBUG
                System.Diagnostics.Debug.WriteLine($"?? Error en ValidarConexionYBaseDatos: {ex.Message}");
#endif
            }

            return false;
        }
    }
